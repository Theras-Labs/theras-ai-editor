// Makes src/vendor/port/game.js from the sources of the port scene.
//
// The source is a first-person scene at a container port in which every asset is made in code.
// Claude Fable 5.2 wrote it; it is a public claude.ai artifact. The code ran in ONE shared scope
// with minified top-level names, so the sections stay in one module and in their original order.
// This script changes three things only:
//   1. It cuts the boot code at the end (the page's own renderer, loop, HUD and error hooks).
//   2. It makes the material factory synchronous (it has no await), so a prop can be built in
//      one step once the module is loaded.
//   3. It adds named exports for the factories that the Theras adapter calls.
//
// Usage (from apps/editor):
//   node scripts/vendor-port.mjs /path/to/source-folder
// The source folder has src/game/three-imports.js and src/game/sections/NN-*.js (the original
// code, formatted and split into sections).
import fs from "node:fs";
import path from "node:path";

const source = process.argv[2];
if (!source) {
  console.error("usage: node scripts/vendor-port.mjs /path/to/source-folder");
  process.exit(1);
}
const gameDir = path.join(source, "src/game");
const outFile = path.resolve("src/vendor/port/game.js");

const read = (file) => fs.readFileSync(file, "utf8");
const sections = fs
  .readdirSync(path.join(gameDir, "sections"))
  .filter((f) => f.endsWith(".js"))
  .sort();

/** The body of a top-level function: from its first line to the first line that is only "}". */
function topLevelBody(text, startIndex) {
  const end = text.indexOf("\n}\n", startIndex);
  if (end < 0) throw new Error("no end of function found");
  return text.slice(startIndex, end + 3);
}

/** `async function name(` -> `function name(`, only when the body has no await. */
function makeSync(text, name) {
  const head = `async function ${name}(`;
  const at = text.indexOf(`\n${head}`);
  if (at < 0) throw new Error(`function ${name} not found`);
  const body = topLevelBody(text, at + 1);
  if (/\bawait\b/.test(body)) throw new Error(`function ${name} has an await: it cannot be made synchronous`);
  return text.replace(`\n${head}`, `\nfunction ${name}(`);
}

const parts = [];
parts.push(read(path.join(gameDir, "three-imports.js")).replace(/^\/\/ Generated by.*\n/, ""));
for (const file of sections) {
  let text = read(path.join(gameDir, "sections", file));
  if (file.startsWith("02-")) text = makeSync(text, "Gg");
  if (file.startsWith("09-")) {
    // Everything from here on is the page boot: window flags, the console.error hook, the boot
    // screen, the original renderer and its animation loop.
    const cut = text.indexOf("\nwindow.__frames = 0;");
    if (cut < 0) throw new Error("boot marker not found in section 09");
    text = text.slice(0, cut + 1);
  }
  parts.push(`// ---- ${file} ----\n${text}`);
}

const header = `// @ts-nocheck
/* eslint-disable */
// A procedural container port: every asset in this file is made by code (no image file, no
// model file, no sound file). Claude Fable 5.2 wrote this code. It is a public claude.ai
// artifact: https://claude.ai/artifact/2UXyB49DrVHFfhTMdNDFTA
// The code is as Fable wrote it: only formatted, joined in one module and cut as described in
// apps/editor/scripts/vendor-port.mjs.
// GENERATED FILE: do not edit. Run scripts/vendor-port.mjs to make it again.
`;

const footer = `
// ---- Theras API (added by scripts/vendor-port.mjs) ----
// The boot code called this to show a fatal start error on the original scene page.
function bM(i) {
  console.error("[port] " + i);
}
export {
  Pr as QUALITY,
  Dy as createEvents,
  il as createRng,
  dr as stubs,
  Gg as createMaterials,
  d3 as createPhysics,
  Yg as createProps,
  Gi as PROP_SIZES,
  C1 as createLevel,
  pv as createBackdrop,
  O1 as createGround,
  Cf as createFx,
  dm as createWeapon,
  Em as createEnemies,
  gM as showcases,
  // The sky of the render section: its noise texture, the sky dome, the environment map made
  // from the dome, the sun values and the fit of the sun's shadow box.
  Oy as createNoiseTexture,
  Hy as createSky,
  Vy as createSkyEnvironment,
  Gy as fitSunShadow,
  Mn as SUN,
  en as SKY,
  oi as BOUNDS,
  // The model builders of the rifle, the drone and the robot hound. The library entries call
  // them directly: the module factories (createWeapon, createEnemies) need a camera, input, a
  // player and physics, and they build pools of 18 robots.
  w_ as buildRifleGeometry,
  Bf as patchRifleMaterial,
  Wv as RIFLE_RAIN,
  mi as RIFLE_SPEC,
  F_ as buildRifleMarkings,
  U_ as buildRifleLens,
  j_ as buildDroneRig,
  Z_ as buildHoundRig,
  pm as assembleRig,
  q_ as solveHoundLeg,
  xm as DRONE_SPEC,
  $v as HOUND_SPEC,
  ym as ROBOT_LENS_COLOR
};
`;

const out = header + parts.join("\n") + footer;
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, out);
console.log(`wrote ${outFile}: ${(out.length / 1024).toFixed(0)} KB, ${out.split("\n").length} lines, ${sections.length} sections`);
